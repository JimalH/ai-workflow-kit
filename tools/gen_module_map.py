#!/usr/bin/env python3
"""Generate MODULE_MAP.md: a compact map of a Python project for AI agents.

Reference implementation for Section 9 (Module Map) of the AI rules. Standard
library only, Python 3.9+. Source files are parsed with `ast` and never imported.
Copy this file into `<PROJECT_ROOT>/tools/` of the project that needs a map.

The map is rewritten only when its body changes, so the `Commit:` header names
the commit the map was generated at; `--check` is the freshness test.

Usage:
    python tools/gen_module_map.py            # write <root>/MODULE_MAP.md
    python tools/gen_module_map.py --check    # exit 1 when the committed map is stale

Options:
    --root DIR       project root (default: nearest parent with .git, else cwd)
    --budget N       max body lines per map before splitting per top-level
                     package (default 1500; the root map becomes the index)
    --exclude GLOB   extra path glob to skip (repeatable)
    --include-tests  include test files and test directories

Output per source file:
    - `pkg/mod.py` - <module docstring, first line> imports: `a.b`, `c` (+N private)
      - `func(args) -> ret` L18 - <docstring, first line>
      - `class Name(Base)` L54 - <docstring, first line> methods: `m` L61, `n` L70

Public = no leading underscore, or listed in `__all__`. A missing docstring is
rendered as `(no docstring)` so a reviewer can flag it. Only Python is parsed;
other languages need a parser of their own with the same output shape.
"""

from __future__ import annotations

import argparse
import ast
import fnmatch
import os
import subprocess
import sys
from collections import Counter
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path, PurePosixPath

MAP_NAME = "MODULE_MAP.md"
MARKER = "<!-- generated by gen_module_map.py - do not edit by hand -->"
VOLATILE_PREFIXES = ("Generated:", "Commit:")

EXCLUDE_DIRS = {
    ".git", ".hg", ".svn", ".venv", "venv", "env", "node_modules", "__pycache__",
    "build", "dist", ".memory", "vendor", "third_party", "site-packages",
    ".ipynb_checkpoints", ".eggs", ".mypy_cache", ".pytest_cache", ".tox",
    ".idea", ".vscode", ".claude",
}
NON_SOURCE_DIRS = {"data", "datasets", "notebooks"}
TEST_DIRS = {"tests", "test", "testing"}
TEST_FILE_GLOBS = ("test_*.py", "*_test.py", "conftest.py")
SOURCE_ROOT_DIRS = {"src", "lib"}
SUMMARY_MAX = 160


@dataclass
class Symbol:
    kind: str  # func | class | const
    line: int
    text: str
    summary: str
    methods: list[tuple[str, int]] = field(default_factory=list)


@dataclass
class SourceFile:
    path: PurePosixPath
    lines: int
    purpose: str
    imports: list[str]
    symbols: list[Symbol]
    private: int
    error: str = ""


# ----------------------------------------------------------------------------
# discovery

def find_root(start: Path) -> Path:
    for candidate in (start, *start.parents):
        if (candidate / ".git").exists():
            return candidate
    return start


def list_all_files(root: Path) -> list[PurePosixPath]:
    """All files under root, honouring .gitignore when git is available."""
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others",
             "--exclude-standard"],
            capture_output=True, check=True,
        ).stdout.decode("utf-8", "surrogateescape")
        files = [PurePosixPath(p) for p in out.split("\0") if p]
    except (OSError, subprocess.CalledProcessError):
        files = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDE_DIRS)
            rel = Path(dirpath).relative_to(root)
            files.extend(PurePosixPath(rel / f) for f in filenames)
    files = [f for f in files if not any(part in EXCLUDE_DIRS for part in f.parts)]
    return sorted(f for f in files if (root / f).is_file())


def is_test(path: PurePosixPath) -> bool:
    if any(part in TEST_DIRS for part in path.parts[:-1]):
        return True
    return any(fnmatch.fnmatch(path.name, g) for g in TEST_FILE_GLOBS)


def select_sources(files: list[PurePosixPath], include_tests: bool,
                   excludes: list[str]) -> list[PurePosixPath]:
    out = []
    for f in files:
        if f.suffix != ".py" or f.name == MAP_NAME:
            continue
        if any(part in NON_SOURCE_DIRS for part in f.parts[:-1]):
            continue
        if not include_tests and is_test(f):
            continue
        if any(fnmatch.fnmatch(f.as_posix(), g) for g in excludes):
            continue
        out.append(f)
    return out


# ----------------------------------------------------------------------------
# module names and imports

def module_names(path: PurePosixPath) -> list[str]:
    """Dotted names a file can be imported as (with and without a src/ root)."""
    parts = list(path.with_suffix("").parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    names = []
    if parts:
        names.append(".".join(parts))
    if len(parts) > 1 and parts[0] in SOURCE_ROOT_DIRS:
        names.append(".".join(parts[1:]))
    return names


def known_modules(sources: list[PurePosixPath]) -> set[str]:
    known: set[str] = set()
    for f in sources:
        for name in module_names(f):
            bits = name.split(".")
            for i in range(1, len(bits) + 1):
                known.add(".".join(bits[:i]))
    return known


def is_internal(name: str, known: set[str]) -> bool:
    bits = name.split(".")
    return any(".".join(bits[:i]) in known for i in range(1, len(bits) + 1))


def package_of(path: PurePosixPath) -> list[str]:
    return list(path.parts[:-1])


def collect_imports(tree: ast.AST, path: PurePosixPath, known: set[str]) -> list[str]:
    found: set[str] = set()
    pkg = package_of(path)
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if is_internal(alias.name, known):
                    found.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                if node.level - 1 > len(pkg):
                    continue
                base = pkg[: len(pkg) - (node.level - 1)]
                stem = ".".join(base + ([node.module] if node.module else []))
            else:
                stem = node.module or ""
            if not stem or not is_internal(stem, known):
                continue
            for alias in node.names:
                cand = f"{stem}.{alias.name}"
                found.add(cand if cand in known else stem)
    return sorted(found)


# ----------------------------------------------------------------------------
# symbols

def first_line(doc: str | None) -> str:
    if not doc:
        return "(no docstring)"
    for line in doc.strip().splitlines():
        line = line.strip()
        if line:
            return line if len(line) <= SUMMARY_MAX else line[: SUMMARY_MAX - 1] + "…"
    return "(no docstring)"


def dunder_all(tree: ast.Module) -> set[str]:
    names: set[str] = set()
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = node.targets
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            targets = [node.target]
        if any(isinstance(t, ast.Name) and t.id == "__all__" for t in targets):
            value = node.value
            if isinstance(value, (ast.List, ast.Tuple)):
                names |= {e.value for e in value.elts
                          if isinstance(e, ast.Constant) and isinstance(e.value, str)}
    return names


def signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    text = f"{node.name}({ast.unparse(node.args)})"
    if node.returns is not None:
        text += f" -> {ast.unparse(node.returns)}"
    if isinstance(node, ast.AsyncFunctionDef):
        text = "async " + text
    return text


def assigned_names(node: ast.stmt) -> list[str]:
    if isinstance(node, ast.Assign):
        return [t.id for t in node.targets if isinstance(t, ast.Name)]
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return [node.target.id]
    return []


def parse_file(root: Path, path: PurePosixPath, known: set[str]) -> SourceFile:
    raw = (root / path).read_bytes()
    text = raw.decode("utf-8-sig", errors="replace")
    lines = text.count("\n") + (1 if text and not text.endswith("\n") else 0)
    try:
        tree = ast.parse(text, filename=str(path))
    except SyntaxError as exc:
        return SourceFile(path, lines, "(syntax error)", [], [], 0,
                          error=f"line {exc.lineno}: {exc.msg}")
    exported = dunder_all(tree)

    def public(name: str) -> bool:
        return not name.startswith("_") or name in exported

    symbols: list[Symbol] = []
    private = 0
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if public(node.name):
                symbols.append(Symbol("func", node.lineno, signature(node),
                                      first_line(ast.get_docstring(node))))
            else:
                private += 1
        elif isinstance(node, ast.ClassDef):
            if not public(node.name):
                private += 1
                continue
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            text_ = f"class {node.name}" + (f"({bases})" if bases else "")
            methods = [(n.name, n.lineno) for n in node.body
                       if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
                       and public(n.name)]
            symbols.append(Symbol("class", node.lineno, text_,
                                  first_line(ast.get_docstring(node)), methods))
        else:
            for name in assigned_names(node):
                if name in exported:
                    symbols.append(Symbol("const", node.lineno, name, "(constant)"))
    symbols.sort(key=lambda s: s.line)
    return SourceFile(path, lines, first_line(ast.get_docstring(tree)),
                      collect_imports(tree, path, known), symbols, private)


# ----------------------------------------------------------------------------
# rendering

def render_file(sf: SourceFile) -> list[str]:
    head = f"- `{sf.path.as_posix()}` - {sf.purpose}"
    if sf.error:
        head += f" ({sf.error})"
    if sf.imports:
        head += " imports: " + ", ".join(f"`{m}`" for m in sf.imports)
    if sf.private:
        head += f" (+{sf.private} private)"
    out = [head]
    for s in sf.symbols:
        line = f"  - `{s.text}` L{s.line} - {s.summary}"
        if s.methods:
            line += " methods: " + ", ".join(f"`{n}` L{ln}" for n, ln in s.methods)
        out.append(line)
    return out


def other_dirs(all_files: list[PurePosixPath], sources: list[PurePosixPath]) -> list[str]:
    source_tops = {f.parts[0] for f in sources if len(f.parts) > 1}
    counts: dict[str, Counter] = {}
    for f in all_files:
        if len(f.parts) < 2 or f.parts[0] in source_tops:
            continue
        counts.setdefault(f.parts[0], Counter())[f.suffix.lstrip(".") or "(none)"] += 1
    out = []
    for top in sorted(counts):
        kinds = ", ".join(f"{n} {ext}" for ext, n in counts[top].most_common(3))
        out.append(f"- `{top}/` - {kinds}")
    return out


def header(regen: str, commit: str, n_files: int, n_lines: int, index: str = "") -> list[str]:
    out = [
        "# MODULE_MAP",
        "",
        MARKER,
        f"Generated: {datetime.now().astimezone().strftime('%Y-%m-%d %H:%M %z')}",
        f"Commit: {commit}",
        f"Files: {n_files} source files, {n_lines:,} lines",
        f"Regenerate: `{regen}`",
        f"Check: `{regen} --check`",
    ]
    if index:
        out.append(f"Index: `{index}`")
    out.append("")
    return out


def build_maps(root: Path, parsed: list[SourceFile], all_files: list[PurePosixPath],
               budget: int, regen: str, commit: str) -> dict[PurePosixPath, list[str]]:
    """Return {map path: lines}. One map, or a root index plus one map per package."""
    sources = [sf.path for sf in parsed]
    n_lines = sum(sf.lines for sf in parsed)
    body = ["## Files", ""]
    for sf in parsed:
        body += render_file(sf)
    others = other_dirs(all_files, sources)
    if others:
        body += ["", "## Other directories", ""] + others

    if len(body) <= budget:
        return {PurePosixPath(MAP_NAME): header(regen, commit, len(parsed), n_lines) + body}

    maps: dict[PurePosixPath, list[str]] = {}
    groups: dict[str, list[SourceFile]] = {}
    root_level: list[SourceFile] = []
    for sf in parsed:
        (groups.setdefault(sf.path.parts[0], []) if len(sf.path.parts) > 1
         else root_level).append(sf)

    index = ["## Packages", ""]
    for top in sorted(groups):
        files = groups[top]
        init = next((f for f in files if f.path.as_posix() == f"{top}/__init__.py"), None)
        purpose = f" - {init.purpose}" if init else ""
        sub_lines = sum(f.lines for f in files)
        index.append(f"- `{top}/`{purpose} - {len(files)} files, {sub_lines:,} lines"
                     f" -> `{top}/{MAP_NAME}`")
        sub = ["## Files", ""]
        for sf in files:
            sub += render_file(sf)
        maps[PurePosixPath(top) / MAP_NAME] = header(
            regen, commit, len(files), sub_lines, index=f"../{MAP_NAME}") + sub
    if root_level:
        index += ["", "## Files", ""]
        for sf in root_level:
            index += render_file(sf)
    if others:
        index += ["", "## Other directories", ""] + others
    maps[PurePosixPath(MAP_NAME)] = header(regen, commit, len(parsed), n_lines) + index
    return maps


# ----------------------------------------------------------------------------
# io

def stable(lines: list[str]) -> list[str]:
    return [l for l in lines if not l.startswith(VOLATILE_PREFIXES)]


def existing_maps(root: Path, all_files: list[PurePosixPath]) -> dict[PurePosixPath, list[str]]:
    found = {}
    for f in all_files:
        if f.name != MAP_NAME:
            continue
        try:
            text = (root / f).read_text(encoding="utf-8-sig")
        except OSError:
            continue
        if MARKER in text:
            found[f] = text.splitlines()
    return found


def git_commit(root: Path) -> str:
    try:
        return subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip() or "-"
    except (OSError, subprocess.CalledProcessError):
        return "-"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--budget", type=int, default=1500)
    ap.add_argument("--exclude", action="append", default=[], metavar="GLOB")
    ap.add_argument("--include-tests", action="store_true")
    args = ap.parse_args(argv)

    root = (args.root or find_root(Path.cwd())).resolve()
    all_files = list_all_files(root)
    sources = select_sources(all_files, args.include_tests, args.exclude)
    if not sources:
        print(f"no Python source files under {root}", file=sys.stderr)
        return 2
    known = known_modules(sources)
    parsed = [parse_file(root, f, known) for f in sources]

    script = Path(__file__).resolve()
    try:
        script_rel = script.relative_to(root).as_posix()
    except ValueError:
        script_rel = script.as_posix()
    regen = f"python {script_rel}" if " " not in script_rel else f'python "{script_rel}"'
    for flag in ("--include-tests",):
        if getattr(args, flag[2:].replace("-", "_")):
            regen += f" {flag}"
    for g in args.exclude:
        regen += f" --exclude {g}"
    if args.budget != 1500:
        regen += f" --budget {args.budget}"

    maps = build_maps(root, parsed, all_files, args.budget, regen, git_commit(root))
    current = existing_maps(root, all_files)

    stale = [p for p in maps if stable(maps[p]) != stable(current.get(p, []))]
    orphans = [p for p in current if p not in maps]
    if args.check:
        for p in stale:
            print(f"stale: {p}")
        for p in orphans:
            print(f"orphan: {p}")
        if stale or orphans:
            print(f"module map out of date; run: {regen}")
            return 1
        print("module map up to date")
        return 0

    for p in stale:
        (root / p).parent.mkdir(parents=True, exist_ok=True)
        (root / p).write_text("\n".join(maps[p]) + "\n", encoding="utf-8", newline="\n")
        print(f"written: {p}")
    for p in orphans:
        (root / p).unlink()
        print(f"removed: {p}")
    if not stale and not orphans:
        print("unchanged")
    errors = [sf for sf in parsed if sf.error]
    for sf in errors:
        print(f"warning: {sf.path}: {sf.error}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
